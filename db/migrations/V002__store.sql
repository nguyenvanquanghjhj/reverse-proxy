CREATE TABLE st_users (
 id UUID PRIMARY KEY, email VARCHAR(254) UNIQUE NOT NULL, display_name VARCHAR(80) NOT NULL,
 password_hash VARCHAR(200) NOT NULL, role VARCHAR(16) NOT NULL CHECK(role IN ('CUSTOMER','ADMIN')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE st_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id UUID REFERENCES st_users(id), csrf VARCHAR(64) NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX st_sessions_expiry ON st_sessions(expires_at);
CREATE TABLE st_login_limits (
 identity_hash CHAR(64) PRIMARY KEY, attempts INTEGER NOT NULL, window_start TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE st_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug VARCHAR(64) UNIQUE NOT NULL,
 name VARCHAR(80) NOT NULL, active BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE st_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_id BIGINT NOT NULL REFERENCES st_categories(id),
 name VARCHAR(160) NOT NULL, brand VARCHAR(64) NOT NULL, description VARCHAR(4000) NOT NULL,
 screen VARCHAR(120) NOT NULL, chipset VARCHAR(120) NOT NULL, ram_gb INTEGER NOT NULL CHECK(ram_gb BETWEEN 1 AND 64),
 battery_mah INTEGER NOT NULL CHECK(battery_mah BETWEEN 500 AND 30000),
 active BOOLEAN NOT NULL DEFAULT false, featured BOOLEAN NOT NULL DEFAULT false,
 version INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX st_products_catalog ON st_products(category_id,active,created_at DESC);
CREATE TABLE st_variants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES st_products(id),
 sku VARCHAR(64) UNIQUE NOT NULL, color VARCHAR(40) NOT NULL, storage_gb INTEGER NOT NULL CHECK(storage_gb BETWEEN 16 AND 4096),
 price_vnd BIGINT NOT NULL CHECK(price_vnd BETWEEN 1000 AND 1000000000), stock INTEGER NOT NULL CHECK(stock BETWEEN 0 AND 1000000),
 active BOOLEAN NOT NULL DEFAULT true, UNIQUE(product_id,color,storage_gb)
);
CREATE INDEX st_variants_product ON st_variants(product_id);
CREATE TABLE st_files (
 id UUID PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES st_products(id), kind VARCHAR(8) NOT NULL CHECK(kind IN ('IMAGE','PDF')),
 display_name VARCHAR(100) NOT NULL, storage_key VARCHAR(64) UNIQUE NOT NULL, mime VARCHAR(32) NOT NULL,
 size_bytes INTEGER NOT NULL CHECK(size_bytes BETWEEN 1 AND 786432), sha256 CHAR(64) NOT NULL,
 position INTEGER NOT NULL DEFAULT 0 CHECK(position BETWEEN 0 AND 1000), active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX st_files_product ON st_files(product_id,kind,position);
CREATE TABLE st_orders (
 id UUID PRIMARY KEY, user_id UUID REFERENCES st_users(id), guest_hash CHAR(64) NOT NULL,
 recipient VARCHAR(80) NOT NULL, phone VARCHAR(20) NOT NULL, address VARCHAR(300) NOT NULL, note VARCHAR(500) NOT NULL,
 subtotal_vnd BIGINT NOT NULL CHECK(subtotal_vnd>=0), shipping_vnd BIGINT NOT NULL CHECK(shipping_vnd>=0), total_vnd BIGINT NOT NULL CHECK(total_vnd=subtotal_vnd+shipping_vnd),
 payment_method VARCHAR(8) NOT NULL DEFAULT 'COD' CHECK(payment_method='COD'),
 payment_status VARCHAR(8) NOT NULL DEFAULT 'UNPAID' CHECK(payment_status IN ('UNPAID','PAID')),
 status VARCHAR(16) NOT NULL DEFAULT 'CREATED' CHECK(status IN ('CREATED','CONFIRMED','PACKING','SHIPPED','DELIVERED','CANCELLED')),
 idempotency_key VARCHAR(128) UNIQUE NOT NULL, request_hash CHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX st_orders_user ON st_orders(user_id,created_at DESC);
CREATE INDEX st_orders_status ON st_orders(status,created_at DESC);
CREATE TABLE st_order_items (
 order_id UUID NOT NULL REFERENCES st_orders(id), variant_id BIGINT NOT NULL REFERENCES st_variants(id),
 product_name VARCHAR(160) NOT NULL, sku VARCHAR(64) NOT NULL, color VARCHAR(40) NOT NULL, storage_gb INTEGER NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 20), unit_price_vnd BIGINT NOT NULL CHECK(unit_price_vnd>0),
 line_total_vnd BIGINT NOT NULL CHECK(line_total_vnd=unit_price_vnd*quantity), PRIMARY KEY(order_id,variant_id)
);
CREATE TABLE st_order_history (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, order_id UUID NOT NULL REFERENCES st_orders(id),
 status VARCHAR(16) NOT NULL, actor_id UUID REFERENCES st_users(id), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX st_history_order ON st_order_history(order_id,id);
